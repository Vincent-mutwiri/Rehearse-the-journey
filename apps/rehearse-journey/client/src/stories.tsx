/**
 * Interactive stories shown next to Joy's mascot.
 *
 * The bot opens a story by sending an RTVI server message
 * `{ type: "story_open", story_id }`; the id must match a key in STORIES.
 *
 * A slide is either plain text (`title` + `body`) or a `render` slot that
 * returns any React node — that is the generic content slot maps, images,
 * or richer widgets plug into later.
 */

import type { ReactNode } from 'react'
import { MapContainer, TileLayer, Polyline, Marker, Popup } from 'react-leaflet'
import L from 'leaflet'
import 'leaflet/dist/leaflet.css'

// ── Route data from the bot (Maps Routes API v2) ────────────────────────────
export interface RouteStep {
  instruction: string
  maneuver?: string
  start?: { latitude?: number; longitude?: number }
  end?: { latitude?: number; longitude?: number }
}

export interface RouteData {
  distance_meters: number
  duration: string
  steps: RouteStep[]
  polyline: { lat: number; lng: number }[]
  label: string
}

export interface StorySlide {
  id: string
  kind?: 'text' | 'custom'
  title?: string
  body?: string
  /** Generic content slot: any React node (map, diagram, widget). */
  render?: () => ReactNode
}

export interface StoryDef {
  id: string
  title: string
  kicker?: string
  slides: StorySlide[]
  /**
   * Optional scene illustration generated by the bot (a data URL,
   * `data:image/jpeg;base64,...`). When present, the StoryCard shows it
   * above the slides as a warm scene-setter. When absent, the card falls
   * back to the slides' own content (the FictionalMap SVG, etc.).
   */
  image?: string
  /**
   * Optional route data from the Maps Routes API (v2), computed by the bot
   * with the maps_api key. When present, the StoryCard's map slide
   * renders a real Leaflet map with the route drawn on it, labelled
   * "candidate path — confirm with your co-designer." When absent, the
   * slide falls back to the FictionalMap SVG.
   */
  route?: RouteData
}

/* ── Fictional map slide ────────────────────────────────────────────────────
 * A tiny SVG floor-plan/map for practice stories. All locations are
 * fictional — labelled as such, never real directions. */

interface MapRoom {
  x: number
  y: number
  w: number
  h: number
  label: string
  sub?: string
  tone?: 'lavender' | 'peach' | 'sage' | 'mist'
}

const ROOM_FILL: Record<NonNullable<MapRoom['tone']>, string> = {
  lavender: '#a89bd4',
  peach: '#f4c6a6',
  sage: '#8fb39b',
  mist: '#e8e2f0',
}

function FictionalMap({
  rooms,
  route,
  marker,
  caption,
}: {
  rooms: MapRoom[]
  route?: [number, number][]
  marker?: { x: number; y: number; label: string }
  caption: string
}) {
  return (
    <figure className="story-map">
      <svg viewBox="0 0 340 210" role="img" aria-label={caption}>
        {rooms.map(room => (
          <g key={room.label}>
            <rect
              x={room.x}
              y={room.y}
              width={room.w}
              height={room.h}
              rx={10}
              fill={ROOM_FILL[room.tone ?? 'mist']}
              stroke="#3a3550"
              strokeOpacity={0.18}
            />
            <text
              x={room.x + room.w / 2}
              y={room.y + room.h / 2 - (room.sub ? 4 : -4)}
              textAnchor="middle"
              className="story-map-label"
            >
              {room.label}
            </text>
            {room.sub && (
              <text
                x={room.x + room.w / 2}
                y={room.y + room.h / 2 + 12}
                textAnchor="middle"
                className="story-map-sub"
              >
                {room.sub}
              </text>
            )}
          </g>
        ))}
        {route && route.length > 1 && (
          <polyline
            points={route.map(([x, y]) => `${x},${y}`).join(' ')}
            fill="none"
            stroke="#3a3550"
            strokeWidth={2.5}
            strokeDasharray="1 7"
            strokeLinecap="round"
          />
        )}
        {marker && (
          <g>
            <circle cx={marker.x} cy={marker.y} r={7} fill="#fbf7f2" stroke="#3a3550" strokeWidth={2} />
            <circle cx={marker.x} cy={marker.y} r={3} fill="#3a3550" />
            <text x={marker.x} y={marker.y - 12} textAnchor="middle" className="story-map-sub">
              {marker.label}
            </text>
          </g>
        )}
      </svg>
      <figcaption>{caption}</figcaption>
    </figure>
  )
}

/* ── Real map slide (Leaflet + OSM, route from Maps Routes API) ────────────────
 * A real interactive map with the route drawn on it. Uses free OSM tiles
 * (no API key for the map itself); the route comes from the bot's Maps
 * Routes API call. Labelled "candidate path — confirm with your co-designer"
 * per the PRD (§2.2 US-4). */

// Fix the default Leaflet marker icon (it breaks with bundlers).
const defaultIcon = L.icon({
  iconUrl: 'https://unpkg.com/leaflet@1.9.4/dist/images/marker-icon.png',
  iconRetinaUrl: 'https://unpkg.com/leaflet@1.9.4/dist/images/marker-icon-2x.png',
  shadowUrl: 'https://unpkg.com/leaflet@1.9.4/dist/images/marker-shadow.png',
  iconSize: [25, 41],
  iconAnchor: [12, 41],
  shadowSize: [41, 41],
  shadowAnchor: [12, 41],
  popupAnchor: [1, -34],
})
L.Marker.prototype.options.icon = defaultIcon

export function RealMap({ route, caption }: { route: RouteData; caption: string }) {
  if (!route.polyline || route.polyline.length < 2) {
    return <p className="story-map-fallback">{caption}</p>
  }
  const pts = route.polyline.map(p => [p.lat, p.lng] as [number, number])
  const start = pts[0]
  const end = pts[pts.length - 1]
  const bounds = L.latLngBounds(pts)
  const km = (route.distance_meters / 1000).toFixed(1)

  return (
    <figure className="story-map story-map-real">
      <MapContainer
        center={bounds.getCenter()}
        zoom={14}
        scrollWheelZoom={false}
        style={{ height: 220, width: '100%', borderRadius: 12 }}
        bounds={bounds}
        boundsOptions={{ padding: [20, 20] }}
      >
        <TileLayer
          url="https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png"
          attribution='&copy; OpenStreetMap contributors'
        />
        <Polyline positions={pts} pathOptions={{ color: '#a89bd4', weight: 4, opacity: 0.8 }} />
        <Marker position={start}>
          <Popup>Start</Popup>
        </Marker>
        <Marker position={end}>
          <Popup>Destination</Popup>
        </Marker>
      </MapContainer>
      <figcaption>
        {caption} — {km} km, {route.steps.length} steps.
        <br />
        <strong>Candidate path — confirm with your co-designer.</strong>
      </figcaption>
    </figure>
  )
}

